// markNoPick ставит NoPick задачам банка из списка list и проверяет, что каждая запись
// списка в банке есть. Порядок ошибок — по ключу, чтобы сообщение было одинаковым от
// запуска к запуску.
func markNoPick(ps []problem, list map[string]string) error {
	index := map[string]int{}
	for i, p := range ps {
		index[p.Pkg+"."+p.Fn] = i
	}
	var missing []string
	for k, why := range list {
		i, ok := index[k]
		if !ok {
			missing = append(missing, k)
			continue
		}
		if why == "" {
			return fmt.Errorf("noPick: у %s нет причины — запиши, что в условии называет приём", k)
		}
		ps[i].NoPick = true
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("noPick: записей нет в банке задач: %v — убери их из списка (nopick.go) или почини имя", missing)
	}
	return nil
}

package cryptography

import "math/bits"

// MulMod возвращает (a·b) mod m без переполнения. Дана готовой: писать её не нужно.
// Гарантируется 0 <= a, b < m.
//
// Зачем: a·b при m больше ~3·10⁹ не помещается в 64 бита, и a*b%m тихо врёт —
// тест простоты начинает объявлять простые составными. Здесь произведение
// считается в 128 битах (старшая и младшая половины), а остаток — делением
// 128-битного числа на m.
func MulMod(a, b, m int) int {
	hi, lo := bits.Mul64(uint64(a), uint64(b))
	_, rem := bits.Div64(hi, lo, uint64(m)) // hi < m, потому что a, b < m
	return int(rem)
}

package miniredis

import (
	"bufio"
	"bytes"
	"testing"
)

// FuzzReadCommand проверяет ОДНО свойство: ReadCommand не должен паниковать ни на каком
// входе — сервер получает эти байты прямо с сокета, до какой-либо проверки, значит вход
// нужно считать полностью враждебным. Это не model-based тест вроде *_rand_test.go в других
// пакетах (там случайные, но ВАЛИДНЫЕ входы сверяются с эталонной моделью) — здесь входы
// сырые и заведомо кривые байты, а движок фаззинга не бросает их наугад, а мутирует в
// сторону путей кода, которые ещё не пройдены (coverage-guided), поэтому находит то, что
// авторские тест-кейсы просто не пришли в голову написать руками.
//
// Затравка "*1\r\n$9223372036854775807\r\nX" — не выдуманный край, а реальный баг: до
// появления maxBulkLen в parseMultibulk (resp.go) этот вход валил ReadCommand паникой
// "makeslice: len out of range" (переполнение int в blen+2) за счёт coverage-guided
// мутации — фаззер нашёл его самостоятельно в первые секунды прогона. Подробности и разбор
// — в главе (src/miniredis.md, раздел про fuzzing).
func FuzzReadCommand(f *testing.F) {
	seeds := []string{
		"*1\r\n$4\r\nPING\r\n",
		"*2\r\n$3\r\nGET\r\n$3\r\nfoo\r\n",
		"PING\r\n",
		"SET foo bar\r\n",
		"",
		"*0\r\n",
		"*-1\r\n",
		"*1\r\n$-1\r\n",
		"*1\r\n$9223372036854775807\r\nX", // исторический баг: переполнение blen+2 (см. выше)
		"*99999999999999999999\r\n",       // заголовок массива не влезает в int
		"$3\r\nfoo\r\n",                   // '$' там, где ожидался элемент массива *N
	}
	for _, s := range seeds {
		f.Add([]byte(s))
	}
	f.Fuzz(func(t *testing.T, data []byte) {
		r := bufio.NewReader(bytes.NewReader(data))
		// Результат и ошибку не проверяем — на произвольных байтах любая ошибка
		// протокола легальна. Единственный инвариант: не паниковать (фаззер сам
		// ловит панику и сохраняет вызвавший её вход в testdata/fuzz/).
		ReadCommand(r)
	})
}

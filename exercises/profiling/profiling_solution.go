package profiling

import (
	"strconv"
	"strings"
)

// FormatScores — исправленная версия. Заготовка складывала строку через
// result += fmt.Sprintf(...) в цикле: строки в Go неизменяемы, поэтому КАЖДЫЙ
// += копирует весь накопленный результат заново — O(n²) байт скопировано на n
// элементов, а не O(n), хотя по количеству итераций цикл выглядит линейным.
// Измеренный CPU-профиль (см. главу) отдаёт под это копирование
// (runtime.concatstrings) больше трети времени — и ещё почти столько же уходит
// в фоновую сборку мусора: тысячи мелких аллокаций на fmt.Sprintf и рост
// строки создают достаточно мусора, чтобы GC начал регулярно вмешиваться.
// Сам fmt.Sprintf (рефлексия и разбор формата) — тоже реальная, но куда
// меньшая доля. Интуиция «наверное, дорого именно форматирование» здесь
// ошибается — ровно то, что и находит профилирование, а не чтение кода.
//
// Первая версия правки — просто strconv.Itoa(n) вместо fmt.Sprintf — уже
// убирает рефлексию, но strconv.Itoa всё равно возвращает НОВУЮ строку на
// каждый вызов: 1000 чисел — 1000 аллокаций, просто дешевле, чем было.
// Полный фикс идёт на шаг дальше: strconv.AppendInt пишет цифры в
// ПЕРЕИСПОЛЬЗУЕМЫЙ байтовый буфер (buf[:0] обнуляет длину, не аллокацию —
// та же память используется заново), а strings.Builder.Grow заранее
// резервирует память под весь отчёт, чтобы буфер не рос по кусочкам. Итог —
// считанные аллокации на весь вызов вместо тысяч.
func FormatScores(nums []int) string {
	var b strings.Builder
	b.Grow(len(nums) * 4) // грубая оценка итогового размера — меньше ростов буфера
	buf := make([]byte, 0, 20)
	for _, n := range nums {
		buf = strconv.AppendInt(buf[:0], int64(n), 10)
		b.Write(buf)
		b.WriteString(", ")
	}
	return b.String()
}
